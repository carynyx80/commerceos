// Generates packages/blockchain/src/abis.ts from Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const names = ["CommerceEscrow", "MerchantRegistry", "FeeController", "Treasury", "DisputeResolver", "AgentPolicyModule", "AgentAccount", "AgentAccountFactory", "TestUSDG", "TestStable", "MockPriceFeed"];
let out = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\n\n";
for (const n of names) {
  const j = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  out += `export const ${id} = ${JSON.stringify(j.abi)} as const;\n\n`;
}
writeFileSync("packages/blockchain/src/abis.ts", out);
console.log(`wrote ${names.length} ABIs`);
